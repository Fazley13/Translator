from deep_translator import GoogleTranslator


LANGUAGE_CODES = {
    "English": "en",
    "French": "fr",
    "German": "de",
    "Spanish": "es",
    "Italian": "it",
    "Portuguese": "pt",
    "Dutch": "nl",
    "Russian": "ru",
    "Chinese": "zh-cn",
    "Hindi": "hi",
    "Bengali": "bn",
}


print("Available languages:", ", ".join(LANGUAGE_CODES.keys()))
print('Type "exit" anytime to quit.\n')

while True:

    src_lang = input("Enter source language (e.g., English) or Exit to quit: ").strip().lower()
    if src_lang == "exit":
        print("Exiting translator. Goodbye!")
        break

    tgt_lang = input("Enter target language (e.g., Bengali): ").strip().lower()
    if tgt_lang == "exit":
        print("Exiting translator. Goodbye!")
        break

    text = input("Enter text to translate: ").strip()
    if text.lower() == "exit":
        print("Exiting translator. Goodbye!")
        break


    src_lang = next((lang for lang in LANGUAGE_CODES if lang.lower() == src_lang), None)
    tgt_lang = next((lang for lang in LANGUAGE_CODES if lang.lower() == tgt_lang), None)


    if not src_lang or not tgt_lang:
        print("Error: Unsupported language. Please select from the available options.\n")
    else:

        translated_text = GoogleTranslator(source=LANGUAGE_CODES[src_lang], target=LANGUAGE_CODES[tgt_lang]).translate(text)
        print(f"Translated text: {translated_text}\n")